-- Wrap long lines
vim.opt.wrap = true

-- Disable spell checking
vim.opt.spell = false

-- Cursor can go to screen edge (no padding)
vim.opt.scrolloff = 0

-- Hide command line when not in use
vim.opt.cmdheight = 0
